#!/usr/bin/env python3
"""Generate C++ class declarations from recovered vtables and inferred inheritance.

usage: gen_classes.py VTABLES.csv HIERARCHY.csv OUT_HEADER MODULE
One class per vtable, named C_<vtable address>. Virtual methods are named vf<slot> so a derived
class's override of slot N has the same name as the base's. Slots a derived class shares with its
base are not repeated; changed slots are declared as overrides, extra slots as new virtuals.
Bases come first. An inferred base is dropped (class becomes a root) if it would create a cycle or
if the derived vtable is shorter than the base's (the slot count from address gaps is unreliable
where vtables are packed, so such edges are flagged, not trusted).
"""
import csv, sys
csv.field_size_limit(1 << 30)

def main(vt_csv, hier_csv, out, module):
    vt = {r["vtable"]: r for r in csv.DictReader(open(vt_csv))}
    slots = {v: r["slot_addrs"].split() for v, r in vt.items()}
    ninst = {v: len(r["installers"].split()) for v, r in vt.items()}
    base = {}; dropped = []
    for r in csv.DictReader(open(hier_csv)):
        if r["base"] and r["base"] in vt:
            base[r["vtable"]] = (r["base"], r["votes"])
    for d in list(base):                                     # drop edges that contradict slot counts or cycle
        b = base[d][0]
        if len(slots[d]) < len(slots[b]):
            dropped.append((d, b, "shorter vtable than base")); del base[d]; continue
        seen = {d}; x = b
        while x in base and x not in seen:
            seen.add(x); x = base[x][0]
        if x in seen and x != b or b == d or (x in base and x in seen):
            dropped.append((d, b, "cycle")); del base[d]
    order, state = [], {}
    def visit(v):
        if state.get(v) == 2: return
        if state.get(v) == 1:
            return
        state[v] = 1
        if v in base: visit(base[v][0])
        state[v] = 2; order.append(v)
    for v in sorted(vt): visit(v)
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_classes.py from %s vtables: do not edit.\n"
                " * One class per vtable (C_<vtable VA>); methods are vf<slot>, signatures unknown.\n"
                " * Bases are inferred from constructor call chains (docs/classes/*_hierarchy.csv). */\n"
                "#ifndef %s_CLASSES_H\n#define %s_CLASSES_H\n\n" % (module, module.upper(), module.upper()))
        for v in order:
            s = slots[v]
            b = base.get(v)
            head = "class C_%s" % v
            if b:
                head += " : public C_%s" % b[0]
            f.write("// vtable 0x%s: %d slot%s, installed by %d function%s%s\n" % (
                v, len(s), "" if len(s) == 1 else "s", ninst[v], "" if ninst[v] == 1 else "s",
                (", base 0x%s (%s vote%s)" % (b[0], b[1], "" if b[1] == "1" else "s")) if b else ""))
            f.write(head + " {\npublic:\n")
            bs = slots[b[0]] if b else []
            for i, a in enumerate(s):
                if i < len(bs) and bs[i] == a:
                    continue                                 # inherited unchanged
                kind = "override" if i < len(bs) else "virtual"
                f.write("    virtual void vf%d();    // %s 0x%s\n" % (i, kind, a))
            f.write("};\n\n")
        f.write("#endif\n")
    roots = sum(1 for v in vt if v not in base)
    print("%d classes (%d roots, %d with a base); %d inferred bases dropped" % (len(vt), roots, len(base), len(dropped)))
    for d, b, why in dropped: print("  dropped %s -> %s: %s" % (d, b, why))

if __name__ == "__main__":
    main(*sys.argv[1:5])
