#!/usr/bin/env python3
"""Make <module>_decls.h compile by forward-declaring the bare struct tags Ghidra uses as types.

usage: fix_decl_types.py SRC_DIR MODULE [MAX_ROUNDS]
Compiles a file that only includes the header, reads the unknown type names out of the MSVC
errors (names in parameter lists, return types of the prototypes that fail) and writes
`typedef struct X X;` for them to <module>_tags.h, which the header includes. Repeats until the
header is clean or nothing new can be found. Needs the ms-check container.
"""
import os, re, subprocess, sys

KEYWORDS = set("void char short int long float double signed unsigned const volatile struct union enum "
               "extern static code bool byte uint ushort uchar ulong sbyte longlong ulonglong "
               "__cdecl __stdcall __fastcall __thiscall".split())

def compile_header(rel, module):
    probe = os.path.join(rel, "_probe_%s.c" % module)
    open(os.path.join(ROOT, probe), "w").write('#include "ghidra_types.h"\n#include "%s_decls.h"\n' % module)
    win = "Z:\\\\work\\\\" + probe.replace("/", "\\\\")
    out = subprocess.run(["docker", "exec", "ms-check", "wine", "Z:\\opt\\msvc7\\bin\\cl.exe", "/c", "/nologo", "/Zs", win],
                         capture_output=True, text=True).stdout.replace("\r", "")
    os.remove(os.path.join(ROOT, probe))
    return out

def main(src, module, rounds=12):
    global ROOT
    ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    rel = os.path.relpath(os.path.abspath(src), ROOT)
    decls = os.path.join(src, module + "_decls.h"); tags = os.path.join(src, module + "_tags.h")
    known = set(re.findall(r"typedef struct (\w+) ", open(tags).read())) if os.path.exists(tags) else set()
    if not os.path.exists(tags):
        open(tags, "w").write("/* Generated by tools/fix_decl_types.py: forward declarations of bare struct tags. */\n")
    body = open(decls).read()
    if "_tags.h" not in body:
        body = body.replace('#include "ghidra_types.h"', '#include "ghidra_types.h"', 1)
        body = re.sub(r"(#define %s_DECLS_H\n\n)" % module.upper(), r'\1#include "%s_tags.h"\n' % module, body, 1)
        open(decls, "w").write(body)
    lines = open(decls).read().split("\n")
    blacklist = set()
    for r in range(int(rounds)):
        out = compile_header(rel, module)
        errs = [l for l in out.split("\n") if "error C" in l]
        # a prototype the SDK headers already declare differently (DllCanUnloadNow, ...): drop ours
        conflict = {int(n) - 1 for n in re.findall(r"_decls\.h\((\d+)\) : error C(?:2373|2371|2381)", out)}
        if conflict:
            dl = open(decls).read().split("\n")
            for i in conflict:
                if i < len(dl) and not dl[i].startswith("/*"):
                    dl[i] = "/* SDK declares this: " + dl[i] + " */"
            open(decls, "w").write("\n".join(dl)); lines[:] = dl
            print("dropped %d prototypes the SDK already declares" % len(conflict)); continue
        # a tag the SDK already defines (LONG, ...) was a false positive: take it back out
        bad = {int(n) - 1 for n in re.findall(r"_tags\.h\((\d+)\) : error C(?:2371|2011|2365)", out)}
        if bad:
            tl = open(tags).read().split("\n")
            for i in bad:
                m = re.match(r"typedef struct (\w+) ", tl[i])
                if m:
                    known.discard(m.group(1)); blacklist.add(m.group(1))
            open(tags, "w").write("\n".join(l for i, l in enumerate(tl) if i not in bad))
            print("removed", sorted(blacklist)); continue
        if not errs:
            print("round %d: header compiles clean, %d tags" % (r, len(known))); return
        new = set(re.findall(r"error C2081: '(\w+)' : name in formal parameter list illegal", out))
        for m in re.finditer(r"_decls\.h\((\d+)\) : error C(?:2143|2146|2061|2065|2144|2054)", out):
            ln = int(m.group(1)) - 1
            if 0 <= ln < len(lines):
                line = lines[ln]
                head = re.split(r"\b(?:FUN|ptr|thunk)_\w+\s*\(|\b\w+\s*\(", line, 1)[0]
                for t in re.findall(r"[A-Za-z_]\w*", head):
                    if t not in KEYWORDS and not t.startswith("__"):
                        new.add(t)
        new -= known | blacklist
        new = {n for n in new if not re.match(r"(param|FUN|ptr)_", n)}
        if not new:
            print("round %d: %d errors left, no new type names:" % (r, len(errs))); print("\n".join(errs[:6])); return
        with open(tags, "a") as f:
            for n in sorted(new):
                f.write("typedef struct %s %s;\n" % (n, n))
        known |= new
        print("round %d: +%d tags (%s)" % (r, len(new), ", ".join(sorted(new)[:6])))

if __name__ == "__main__":
    main(*sys.argv[1:4])
