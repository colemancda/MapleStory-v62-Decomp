#!/usr/bin/env python3
"""Build <module>_decls.h for a directory of raw Ghidra C files.

usage: gen_decls.py SRC_DIR MODULE GLOBALS.h
Collects each file's function signature, emits prototypes, and adds K&R `int f();`
declarations for FUN_/thunk_ callees that have no file (duplicates, excluded code).
Also makes every .c file include the header.
"""
import glob, os, re, sys

SIG = re.compile(r"\n\n((?:[A-Za-z_][\w \*]*?)\b([A-Za-z_]\w*)\(([^)]*)\))\s*\n\s*\{", re.S)

def fix_types(path):
    """DataTypeWriter prepends built-in typedefs that clash with ghidra_types.h and the SDK, and
    writes unknown-size classes as empty structs, which MSVC C rejects."""
    if not os.path.exists(path):
        return
    t = open(path).read()
    m = re.search(r"^typedef (?:struct|union|enum) ", t, re.M)
    head = '/* Generated by ghidra_scripts/ExportTypes.java (built-in typedefs removed by tools/gen_decls.py). */\n#include "ghidra_types.h"\n\n'
    t = head + (t[m.start():] if m else "")
    t = re.sub(r"\{ /\* PlaceHolder (?:Structure|Union) \*/\n\};", "{ undefined1 _unknown_size; };", t)
    # C++ template instantiations (_CIP<IBinding,...>) and qualified names are not C identifiers;
    # they belong to the C++ tier. Drop their declarations so they cannot break every file.
    blocks = t.split("\n\n")
    t = "\n\n".join(b for b in blocks if not re.search(r"[<>&]|::", b))
    open(path, "w").write(t)

def main(src, module, globals_h):
    fix_types(os.path.join(src, module + "_types.h"))
    protos, defined = [], set()
    files = sorted(glob.glob(os.path.join(src, "*.c")))
    for f in files:
        t = open(f).read()
        m = SIG.search(t)
        if m:
            defined.add(m.group(2))
            proto = re.sub(r"\s+", " ", m.group(1)) + ";"
            if not re.search(r"[<>&]|::|~", proto):
                protos.append(proto)
    callees = set()
    for f in files:
        callees |= set(re.findall(r"\b((?:FUN|thunk_FUN|ptr)_[0-9a-fA-F]{6,8})\b", open(f).read()))
    out = os.path.join(src, module + "_decls.h")
    with open(out, "w") as h:
        h.write("/* Generated by tools/gen_decls.py: do not edit. */\n#ifndef %s_DECLS_H\n#define %s_DECLS_H\n\n" % (module.upper(), module.upper()))
        if os.path.exists(os.path.join(src, module + "_types.h")):
            h.write('#include "%s_types.h"\n' % module)
        h.write('#include "%s"\n\n' % os.path.basename(globals_h))
        h.write("\n".join(sorted(protos)) + "\n\n")
        h.write("/* callees without their own file yet */\n")
        h.write("\n".join("int %s();" % c for c in sorted(callees - defined)) + "\n\n#endif\n")
    # Ghidra's listing types most globals as undefinedN; the decompiler's own inference is only in
    # the output. Recover function-pointer globals from how they are called or compared.
    fp = set()
    for f in files:
        t = open(f).read()
        fp |= set(re.findall(r"\(\*(_?DAT_[0-9a-fA-F]+)\)\s*\(", t))
        fp |= set(re.findall(r"\b(_?DAT_[0-9a-fA-F]+) [!=]= \(code \*\)", t))
    if fp and os.path.exists(os.path.join(src, os.path.basename(globals_h))):
        gp = os.path.join(src, os.path.basename(globals_h))
        gt = open(gp).read()
        for name in fp:
            gt = re.sub(r"extern undefined\d %s;" % re.escape(name.lstrip("_")), "extern code *%s;" % name.lstrip("_"), gt)
        open(gp, "w").write(gt)
        print(len(fp), "function-pointer globals recovered")
    # Names the decompiler invents for any referenced address, with no symbol in the listing.
    if os.path.exists(os.path.join(src, os.path.basename(globals_h))):
        gp = os.path.join(src, os.path.basename(globals_h))
        gt = open(gp).read()
        have = set(re.findall(r"\b(\w+)(?:\[\d+\])?;", gt)) | set(re.findall(r"#define _(\w+) ", gt))
        used = set()
        for f in files:
            used |= set(re.findall(r"\b(_?(?:DAT|PTR_FUN|PTR_DAT|PTR_LAB|UNK|LAB|s_\w+?|u_\w+?)_[0-9a-fA-F]{8})\b", open(f).read()))
        add = []
        for name in sorted(used):
            base = name.lstrip("_")
            if base in have or name in have:
                continue
            if base.startswith("LAB_"):
                add.append("extern code %s;" % base)
            elif base.startswith(("PTR_FUN_", "PTR_LAB_")) and not base.startswith("PTR_s_"):
                add.append("extern code *%s;" % base)
            elif base.startswith("UNK_"):
                add.append("extern undefined1 %s;" % base)
            elif base.startswith("PTR_s_"):
                add.append("extern char *%s;" % base)
            elif base.startswith(("s_", "u_")):
                continue
            else:
                add.append("extern undefined4 %s;" % base)
            if name.startswith("_") and base.startswith("DAT_"):
                add.append("#define %s %s" % (name, base))
        if add:
            open(gp, "a").write("\n/* referenced but not defined in the listing (tools/gen_decls.py) */\n" + "\n".join(add) + "\n")
        print(len(add), "extra declarations")
    inc = '#include "%s_decls.h"' % module
    for f in files:
        t = open(f).read()
        if inc not in t:
            t = t.replace('#include "ghidra_types.h"', '#include "ghidra_types.h"\n' + inc, 1)
            open(f, "w").write(t)
    print(len(protos), "prototypes,", len(callees - defined), "undefined callees ->", out)

if __name__ == "__main__":
    main(*sys.argv[1:4])
