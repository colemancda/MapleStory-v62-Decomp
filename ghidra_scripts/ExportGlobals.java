// Writes extern declarations for every named global data item of the current program.
// Usage (headless post-script): -postScript ExportGlobals.java OUT.h
import ghidra.app.script.GhidraScript;
import ghidra.program.model.data.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;
import java.io.*;

public class ExportGlobals extends GhidraScript {
    private String ctype(DataType dt, int len, String name) {
        // returns "TYPE NAME" or "TYPE NAME[N]"
        if (dt instanceof Array) {
            Array a = (Array) dt;
            return ctype(a.getDataType(), a.getElementLength(), name + "[" + a.getNumElements() + "]");
        }
        String t;
        if (dt instanceof Pointer) t = "undefined4";
        else if (dt instanceof Structure || dt instanceof Union || dt instanceof ghidra.program.model.data.Enum || dt instanceof TypeDef) t = null;
        else t = dt.getName();
        if (t != null && t.matches("undefined[1248]?|byte|sbyte|char|uchar|short|ushort|int|uint|long|ulong|longlong|ulonglong|float|double|bool|dword|word")) {
            if (t.equals("dword")) t = "uint"; else if (t.equals("word")) t = "ushort";
            return t + " " + name;
        }
        if (len == 1 || len == 2 || len == 4 || len == 8) return "undefined" + len + " " + name;
        return "undefined1 " + name + "[" + Math.max(len, 1) + "]";
    }
    @Override
    public void run() throws Exception {
        File out = new File(getScriptArgs()[0]);
        int n = 0;
        try (PrintWriter pw = new PrintWriter(new FileWriter(out))) {
            pw.println("/* Generated by ghidra_scripts/ExportGlobals.java from " + currentProgram.getName() + ". */");
            for (Data d : currentProgram.getListing().getDefinedData(true)) {
                Symbol s = d.getPrimarySymbol();
                if (s == null || s.getSource() == SourceType.DEFAULT && !s.getName().matches("DAT_.*|s_.*|u_.*")) continue;
                String name = s.getName().replaceAll("[^A-Za-z0-9_]", "_");
                if (name.startsWith("s_")) { pw.println("extern char " + name + "[" + Math.max(d.getLength(), 1) + "];"); n++; continue; }
                if (name.startsWith("u_")) { pw.println("extern ushort " + name + "[" + Math.max(d.getLength() / 2, 1) + "];"); n++; continue; }
                pw.println("extern " + ctype(d.getDataType(), d.getLength(), name) + ";");
                if (name.startsWith("DAT_")) pw.println("#define _" + name + " " + name);
                n++;
            }
        }
        println("ExportGlobals: " + n + " globals -> " + out);
    }
}
