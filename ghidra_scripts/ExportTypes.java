// Writes the program's own structures, unions, enums and typedefs as C declarations.
// Usage (headless post-script): -postScript ExportTypes.java OUT.h
import ghidra.app.script.GhidraScript;
import ghidra.program.model.data.*;
import java.io.*;
import java.util.*;

public class ExportTypes extends GhidraScript {
    @Override
    public void run() throws Exception {
        File out = new File(getScriptArgs()[0]);
        DataTypeManager dtm = currentProgram.getDataTypeManager();
        List<DataType> list = new ArrayList<>();
        Iterator<DataType> it = dtm.getAllDataTypes();
        while (it.hasNext()) {
            DataType dt = it.next();
            if (!(dt instanceof Structure || dt instanceof Union || dt instanceof ghidra.program.model.data.Enum)) continue;
            SourceArchive sa = dt.getSourceArchive();
            if (sa != null && sa.getArchiveType() != ArchiveType.PROGRAM && sa.getArchiveType() != ArchiveType.BUILT_IN) continue;
            // PE headers, SEH structs and Windows types are provided by the SDK headers; keep the
            // program's own recovered classes (Ghidra files them under /Demangler)
            if (!dt.getCategoryPath().toString().startsWith("/Demangler")) continue;
            list.add(dt);
        }
        try (PrintWriter pw = new PrintWriter(new FileWriter(out))) {
            pw.println("/* Generated by ghidra_scripts/ExportTypes.java from " + currentProgram.getName() + ". */");
            pw.println("#include \"ghidra_types.h\"");
            DataTypeWriter w = new DataTypeWriter(dtm, pw);
            w.write(list, monitor);
        }
        println("ExportTypes: " + list.size() + " types -> " + out);
    }
}
